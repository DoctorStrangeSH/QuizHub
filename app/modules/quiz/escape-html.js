// Escape user-visible question content before interpolating it into HTML templates.
// The quiz bank can contain markup-like characters that must remain plain text.
export function escapeHTML(value) {
    return String(value ?? '').replace(/[&<>"']/g, character => ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#39;'
    })[character]);
}
