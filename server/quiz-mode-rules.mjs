// Pure server-owned primitives that preserve the current V1 browser mode rules.
// These functions are not wired to production callables yet. The server must call
// them only after authenticating the player and validating the canonical session.

const DUEL_AI_CHANCES = Object.freeze({
    easy: 0.4,
    medium: 0.6,
    hard: 0.8
});

function requireNonNegativeInteger(value, code) {
    if (!Number.isSafeInteger(value) || value < 0) throw new Error(code);
}

export function getDuelAiChance(difficulty = 'easy') {
    return DUEL_AI_CHANCES[difficulty] ?? DUEL_AI_CHANCES.easy;
}

// randomValue is generated by the trusted server, never accepted from the client.
// It follows Math.random() semantics: [0, 1).
export function resolveDuelAiAnswer({ difficulty = 'easy', randomValue }) {
    if (typeof randomValue !== 'number' || !Number.isFinite(randomValue) ||
        randomValue < 0 || randomValue >= 1) {
        throw new Error('INVALID_RANDOM_VALUE');
    }
    return randomValue < getDuelAiChance(difficulty);
}

export function resolveDuelOutcome({ playerScore, aiScore }) {
    requireNonNegativeInteger(playerScore, 'INVALID_PLAYER_SCORE');
    requireNonNegativeInteger(aiScore, 'INVALID_AI_SCORE');
    return playerScore > aiScore ? 'win' : playerScore === aiScore ? 'draw' : 'loss';
}

export function applySurvivalAnswer(state, { correct, points }) {
    if (!state || typeof state !== 'object') throw new Error('INVALID_SURVIVAL_STATE');
    requireNonNegativeInteger(state.lives, 'INVALID_LIVES');
    requireNonNegativeInteger(state.currentStreak, 'INVALID_STREAK');
    requireNonNegativeInteger(state.bestStreak, 'INVALID_BEST_STREAK');
    requireNonNegativeInteger(state.score, 'INVALID_SCORE');
    requireNonNegativeInteger(points, 'INVALID_POINTS');
    if (typeof correct !== 'boolean') throw new Error('INVALID_ANSWER_RESULT');

    const currentStreak = correct ? state.currentStreak + 1 : 0;
    return {
        lives: correct ? state.lives : Math.max(0, state.lives - 1),
        currentStreak,
        bestStreak: Math.max(state.bestStreak, currentStreak),
        score: state.score + (correct ? points : 0)
    };
}

export function calculateTimeTrialPoints({ correct, points, remainingMs }) {
    if (typeof correct !== 'boolean') throw new Error('INVALID_ANSWER_RESULT');
    requireNonNegativeInteger(points, 'INVALID_POINTS');
    requireNonNegativeInteger(remainingMs, 'INVALID_REMAINING_TIME');
    if (!correct) return 0;

    // Existing UI awards +5 when ceil(remainingMs / 1000) > 10,
    // which is exactly equivalent to remainingMs > 10,000.
    return points + (remainingMs > 10_000 ? 5 : 0);
}

export function hasModeWin({ correctAnswers, totalQuestions }) {
    requireNonNegativeInteger(correctAnswers, 'INVALID_CORRECT_ANSWERS');
    requireNonNegativeInteger(totalQuestions, 'INVALID_TOTAL_QUESTIONS');
    if (totalQuestions < 1 || correctAnswers > totalQuestions) {
        throw new Error('INVALID_QUIZ_RESULT');
    }
    return correctAnswers >= Math.ceil(totalQuestions * 0.7);
}
