import {
    resolveDuelAiAnswer,
    resolveDuelOutcome,
    applySurvivalAnswer,
    calculateTimeTrialPoints
} from './quiz-mode-rules.mjs';

const MODES = new Set(['duel', 'survival', 'timetrial']);

export function createModeState(mode, { difficulty = 'easy', totalQuestions } = {}) {
    if (!MODES.has(mode)) throw new Error('UNSUPPORTED_QUIZ_MODE');
    if (!Number.isSafeInteger(totalQuestions) || totalQuestions < 1 || totalQuestions > 100) {
        throw new Error('INVALID_TOTAL_QUESTIONS');
    }

    if (mode === 'duel') {
        return {
            mode,
            difficulty: ['easy', 'medium', 'hard'].includes(difficulty) ? difficulty : 'easy',
            totalQuestions: Math.min(totalQuestions, 7),
            roundsPlayed: 0,
            playerScore: 0,
            aiScore: 0,
            playerCorrect: 0,
            aiCorrect: 0
        };
    }
    if (mode === 'survival') {
        return {
            mode,
            totalQuestions,
            answeredQuestions: 0,
            correctAnswers: 0,
            lives: 3,
            currentStreak: 0,
            bestStreak: 0,
            score: 0
        };
    }
    return {
        mode,
        totalQuestions: Math.min(totalQuestions, 10),
        answeredQuestions: 0,
        correctAnswers: 0,
        score: 0
    };
}

// Call only inside the trusted service after validating the canonical answer.
// aiRandomValue must be generated by the server; remainingMs must be derived
// from the server-owned question deadline, never copied from client input.
export function applyModeAnswer(state, { correct, points, remainingMs, aiRandomValue }) {
    if (!state || !MODES.has(state.mode)) throw new Error('INVALID_MODE_STATE');
    if (typeof correct !== 'boolean') throw new Error('INVALID_ANSWER_RESULT');
    if (!Number.isSafeInteger(points) || points < 0) throw new Error('INVALID_POINTS');

    if (state.mode === 'duel') {
        if (state.roundsPlayed >= state.totalQuestions) throw new Error('MODE_FINISHED');
        const aiCorrect = resolveDuelAiAnswer({
            difficulty: state.difficulty,
            randomValue: aiRandomValue
        });
        const next = {
            ...state,
            roundsPlayed: state.roundsPlayed + 1,
            playerScore: state.playerScore + (correct ? points : 0),
            aiScore: state.aiScore + (aiCorrect ? points : 0),
            playerCorrect: state.playerCorrect + (correct ? 1 : 0),
            aiCorrect: state.aiCorrect + (aiCorrect ? 1 : 0)
        };
        return {
            state: next,
            round: { playerCorrect: correct, aiCorrect, points: correct ? points : 0 },
            finished: next.roundsPlayed === next.totalQuestions
        };
    }

    if (state.answeredQuestions >= state.totalQuestions ||
        (state.mode === 'survival' && state.lives <= 0)) throw new Error('MODE_FINISHED');
    if (state.mode === 'survival') {
        const next = applySurvivalAnswer(state, { correct, points });
        const updated = { ...state, ...next, answeredQuestions: state.answeredQuestions + 1,
            correctAnswers: state.correctAnswers + (correct ? 1 : 0) };
        return {
            state: updated,
            round: { correct, points: correct ? points : 0 },
            finished: updated.lives === 0 || updated.answeredQuestions === updated.totalQuestions
        };
    }

    if (!Number.isSafeInteger(remainingMs) || remainingMs < 0 || remainingMs > 15_000) {
        throw new Error('INVALID_REMAINING_TIME');
    }
    const awarded = calculateTimeTrialPoints({ correct, points, remainingMs });
    const updated = {
        ...state,
        answeredQuestions: state.answeredQuestions + 1,
        correctAnswers: state.correctAnswers + (correct ? 1 : 0),
        score: state.score + awarded
    };
    return {
        state: updated,
        round: { correct, points: awarded, speedBonus: awarded - (correct ? points : 0) },
        finished: updated.answeredQuestions === updated.totalQuestions
    };
}

export function getModeResult(state) {
    if (!state || !MODES.has(state.mode)) throw new Error('INVALID_MODE_STATE');
    if (state.mode === 'duel') {
        const outcome = resolveDuelOutcome({
            playerScore: state.playerScore,
            aiScore: state.aiScore
        });
        return {
            mode: state.mode,
            outcome,
            score: state.playerScore,
            correctAnswers: state.playerCorrect,
            totalQuestions: state.totalQuestions,
            aiScore: state.aiScore,
            aiCorrect: state.aiCorrect,
            wins: outcome === 'win' ? 1 : 0
        };
    }
    if (state.mode === 'survival') {
        return {
            mode: state.mode,
            score: state.score,
            correctAnswers: state.correctAnswers,
            totalQuestions: state.totalQuestions,
            answeredQuestions: state.answeredQuestions,
            bestStreak: state.bestStreak,
            livesRemaining: state.lives
        };
    }
    return {
        mode: state.mode,
        score: state.score,
        correctAnswers: state.correctAnswers,
        totalQuestions: state.totalQuestions,
        answeredQuestions: state.answeredQuestions
    };
}
